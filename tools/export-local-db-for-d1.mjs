#!/usr/bin/env node
/**
 * Export current local Attendly user and academic data as D1-compatible INSERTs.
 * - Preserves IDs, password hashes, semesters, timetable, subjects and attendance.
 * - Intentionally does NOT export sessions; every user must sign in again after migration.
 * - Output contains personal data and password hashes: never commit/share it publicly.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const localProject = path.join(root, 'attendance-management-v1');
const dbFile = path.join(localProject, 'backend', 'data', 'attendance.db');
const outputDir = path.join(root, 'cloudflare', 'migration-data');
const outputFile = path.join(outputDir, 'existing-attendly-data.sql');

if (!fs.existsSync(dbFile)) {
  console.error(`Local database not found: ${dbFile}`);
  console.error('Run this from the extracted Attendly SaaS project after copying your backend/data/attendance.db into the included local project folder.');
  process.exit(1);
}
const require = createRequire(path.join(localProject, 'backend', 'package.json'));
let Database;
try { Database = require('better-sqlite3'); }
catch {
  console.error('better-sqlite3 was not found. Run npm install inside attendance-management-v1/backend first.');
  process.exit(1);
}
const db = new Database(dbFile, { readonly: true, fileMustExist: true });
db.pragma('foreign_keys = ON');

const quote = (value) => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'NULL';
  if (Buffer.isBuffer(value)) return `X'${value.toString('hex')}'`;
  return `'${String(value).replace(/'/g, "''")}'`;
};
const hasTable = (name) => !!db.prepare("SELECT 1 AS ok FROM sqlite_master WHERE type='table' AND name=?").get(name);
const columns = (name) => new Set(db.prepare(`PRAGMA table_info(${name})`).all().map((r) => r.name));
const emit = (table, fields, rows) => rows.map((row) =>
  `INSERT INTO ${table} (${fields.join(', ')}) VALUES (${fields.map((f) => quote(row[f])).join(', ')});`
).join('\n');

const statements = [
  '-- Generated by tools/export-local-db-for-d1.mjs. Contains personal data and password hashes.',
  '-- Sessions intentionally omitted; users must authenticate again after migration.',
];

if (!hasTable('app_user')) throw new Error('app_user table is missing in the local database.');
const userCols = columns('app_user');
const users = db.prepare('SELECT * FROM app_user ORDER BY id').all().map((u) => ({
  id: u.id,
  username: u.username,
  email: userCols.has('email') ? (u.email ?? null) : null,
  password_hash: u.password_hash,
  role: userCols.has('role') ? (u.role ?? 'STUDENT') : 'STUDENT',
  account_status: userCols.has('account_status') ? (u.account_status ?? 'ACTIVE') : 'ACTIVE',
  created_at: u.created_at ?? new Date().toISOString(),
  updated_at: userCols.has('updated_at') ? (u.updated_at ?? u.created_at ?? new Date().toISOString()) : (u.created_at ?? new Date().toISOString()),
}));
statements.push(emit('app_user', ['id','username','email','password_hash','role','account_status','created_at','updated_at'], users));

const exportTable = (table, fields, required = true) => {
  if (!hasTable(table)) {
    if (required) throw new Error(`Required table ${table} is missing.`);
    return;
  }
  const sourceColumns = columns(table);
  const selectFields = fields.filter((field) => sourceColumns.has(field));
  const rows = db.prepare(`SELECT ${selectFields.join(', ')} FROM ${table} ORDER BY id`).all();
  if (rows.length) statements.push(emit(table, selectFields, rows));
};

exportTable('semesters', ['id','user_id','name','start_date','end_date','target_percentage','mass_bunk_policy','created_at']);
exportTable('timetable', ['id','semester_id','weekday','class_count']);
exportTable('subjects', ['id','semester_id','name','code','target_percentage','created_at'], false);
exportTable('timetable_subjects', ['id','semester_id','weekday','class_number','subject_id'], false);
exportTable('attendance', ['id','semester_id','attendance_date','class_number','status','subject_id','created_at','updated_at']);

// Give each imported account an active Free subscription unless one already exists.
// Plan IDs are looked up by code, so this does not rely on a hard-coded numeric ID.
statements.push(`INSERT INTO user_subscriptions (user_id, plan_id, status, starts_at, expires_at, amount_paid_inr)
SELECT u.id, p.id, 'ACTIVE', u.created_at, NULL, 0
FROM app_user u
JOIN subscription_plans p ON p.code = 'FREE'
WHERE NOT EXISTS (
  SELECT 1 FROM user_subscriptions s WHERE s.user_id = u.id AND s.status = 'ACTIVE'
);`);
fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(outputFile, statements.filter(Boolean).join('\n\n') + '\n', 'utf8');
db.close();
console.log('D1 migration data export created:');
console.log(outputFile);
console.log(`Users: ${users.length}`);
console.log('Sessions: not exported (security: users will sign in again).');
console.log('Next: apply the D1 schema migrations first, then import this SQL file.');
